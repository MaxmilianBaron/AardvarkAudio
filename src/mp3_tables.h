struct TransformTables {
    double imdct[4][36][18]{};
    double short_imdct[12][6]{};
    double synthesis[64][32]{};
    double window[512]{};
    double alias_cos[8]{}, alias_sin[8]{};
    TransformTables() {
        constexpr double pi = 3.141592653589793238462643383279502884;
        for (unsigned type = 0; type < 4; ++type) for (unsigned n = 0; n < 36; ++n) {
            double w = std::sin(pi * (n + 0.5) / 36);
            if (type == 1 && n >= 18) w = n < 24 ? 1 : n < 30 ? std::sin(pi * (n - 18 + 0.5) / 12) : 0;
            if (type == 3 && n < 18) w = n < 6 ? 0 : n < 12 ? std::sin(pi * (n - 6 + 0.5) / 12) : 1;
            for (unsigned k = 0; k < 18; ++k) imdct[type][n][k] = w * std::cos(pi / 72 * (2 * n + 19) * (2 * k + 1));
        }
        for (unsigned n = 0; n < 12; ++n) for (unsigned k = 0; k < 6; ++k)
            short_imdct[n][k] = std::sin(pi * (n + 0.5) / 12) * std::cos(pi / 24 * (2 * n + 7) * (2 * k + 1));
        for (unsigned n = 0; n < 64; ++n) for (unsigned k = 0; k < 32; ++k)
            synthesis[n][k] = std::cos(pi / 64 * (n + 16) * (2 * k + 1));
        for (unsigned n = 0; n <= 256; ++n) window[n] = synthesis_half[n] / 65536.0;
        for (unsigned n = 257; n < 512; ++n) window[n] = window[512 - n] * (n % 64 ? -1 : 1);
        constexpr double c[] = {-0.6,-0.535,-0.33,-0.185,-0.095,-0.041,-0.0142,-0.0037};
        for (unsigned n = 0; n < 8; ++n) { alias_cos[n] = 1 / std::sqrt(1 + c[n] * c[n]); alias_sin[n] = c[n] * alias_cos[n]; }
    }
};

